uint16_t Cpu::ReadNextUint16()
{
  _addressBus = _pc.hl;
  uint8_t l = ReadAddress(_pc.hl);
  _pc.hl += 1;
  uint8_t h = ReadAddress(_pc.hl);
  _pc.hl += 1;

  return (h << 8) | l;
}

