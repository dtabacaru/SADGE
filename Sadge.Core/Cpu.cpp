{
  InitBanks();
  m_execution_stopwatch.Start();
}

void Cpu::Main()
{
  TickEdge(_tEdge, _tLevel, _tEdgeCount);

  _tEdge == EdgeType::RISING ? RisingTEvent() : FallingTEvent();
}

uint8_t Cpu::ReadNextUint8()
{
  _addressBus = _pc.hl;
  uint8_t val = ReadAddress(_addressBus);
  _pc.hl += 1;

  return val;
}

