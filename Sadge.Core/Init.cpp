Status Cpu::SetRom(const std::filesystem::path& rom_path, std::vector<uint8_t> rom)
{
  Status status;

  if (rom.empty())
  {
    std::string msg = "ROM is empty.";

    status.SetMsg(msg);
    status.SetValid(false);
    return status;
  }

  if (rom.size() < (static_cast<size_t>(BANK_SIZE) * 2))
  {
    std::string msg = "ROM is too small to be a GameBoy ROM.";

    status.SetMsg(msg);
    status.SetValid(false);
    return status;
  }

  if (rom.size() % BANK_SIZE != 0)
  {
    std::string msg = "ROM is not a multiple of 16K.";

    status.SetMsg(msg);
    status.SetValid(false);
    return status;
  }

  m_rom_file_path = rom_path;
  m_rom = std::move(rom);

  status = ParseHeader();

  return status;
}

void Cpu::InitBanks()
{
  m_num_rom_banks = m_rom.size() / BANK_SIZE;
  mRomBanks = std::vector<std::vector<uint8_t>>(m_num_rom_banks);

  for (int rom_bank_num = 0; rom_bank_num < m_num_rom_banks; rom_bank_num += 1)
  {
    mRomBanks[rom_bank_num] = std::vector<uint8_t>(BANK_SIZE);
    std::copy(m_rom.begin() + BANK_SIZE * rom_bank_num, m_rom.begin() + BANK_SIZE * rom_bank_num + BANK_SIZE, mRomBanks[rom_bank_num].begin());
  }

  mNumRomBanks = RamSizeToNumBanks(m_rom_header.GetRamSize());
  mRamBanks = std::vector<std::vector<uint8_t>>(mNumRomBanks);

  for (int ram_bank_num = 0; ram_bank_num < mNumRomBanks; ram_bank_num += 1)
    mRamBanks[ram_bank_num] = std::vector<uint8_t>(ERAM_SIZE);

  if (mBattery)
  {
    mSaveFilePath = m_rom_file_path;
    mSaveFilePath.replace_extension(SAVE_EXTENSION);

    std::ifstream eram_file(mSaveFilePath, std::ios_base::binary);

    if (eram_file)
      for (int ram_bank_num = 0; ram_bank_num < mNumRomBanks; ram_bank_num += 1)
        eram_file.read((char*)mRamBanks[ram_bank_num].data(), ERAM_SIZE);
  }

  std::copy(BOOT_ROM.begin(), BOOT_ROM.end(), mRomBanks[0].begin());
}

Status Cpu::InsertRom(const std::filesystem::path& rom_path)
{
  Status status;

  size_t rom_size = std::filesystem::file_size(rom_path);

  if (rom_size > MAX_ROM_SIZE)
  {
    std::string msg = "ROM too large to load.";

    status.SetMsg(msg);
    return status;
  }

  std::ifstream rom_stream(rom_path, std::ios_base::binary);

  if (!rom_stream)
  {
    std::string msg = "Could not open ROM file.";

    status.SetMsg(msg);
    return status;
  }

  std::vector<uint8_t> rom;
  rom.resize(rom_size);

  rom_stream.read(reinterpret_cast<char*>(rom.data()), rom_size);

  if (!rom_stream)
  {
    std::string msg = "Could not read ROM file.";

    status.SetMsg(msg);
    return status;
  }

  SetRom(rom_path, std::move(rom));

  return status;
}


uint8_t Cpu::GetTitleHash(std::string title)
{
  uint8_t sum = 0;

  for (int i = 0; i < title.length(); i += 1)
    sum += (uint8_t)title[i];

  return sum;
}

